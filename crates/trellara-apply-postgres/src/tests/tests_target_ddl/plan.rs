use super::*;

#[test]
fn target_ddl_transaction_plan_accepts_safe_additive_sql() {
    let plan = plan_target_ddl_transaction(safe_plan()).expect("ddl transaction plan");

    assert_eq!(plan.barrier_id, "ddl-barrier-123");
    assert_eq!(plan.statement_count, 1);
    assert_eq!(plan.release_gate, "post_ddl_dml_release");
    assert_eq!(plan.plan_sha256.len(), 64);
    assert_eq!(plan.statement_sha256s.len(), 1);
    assert_eq!(plan.statement_sha256s[0].len(), 64);
    assert_eq!(plan.statements[0].operation, "ddl");
    assert_eq!(plan.statements[0].total_order, 1);
    assert_eq!(
        plan.statements[0].sql,
        "ALTER TABLE \"public\".\"sales\" ADD COLUMN IF NOT EXISTS \"discount_code\" text;"
    );
    assert!(plan.statements[0].values.is_empty());
    assert!(!plan.statements[0].requires_row_match);
    assert!(plan
        .steps
        .iter()
        .any(|step| step.contains("target schema transaction")));
    validate_ddl_transaction_plan(&plan).expect("executable plan validates");
}

#[test]
fn target_ddl_transaction_plan_accepts_retry_safe_additive_sql() {
    let mut input = safe_plan();
    input.statements[0].sql =
        "ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS discount_code text;".to_string();

    let plan = plan_target_ddl_transaction(input).expect("retry-safe ddl transaction plan");

    assert_eq!(
        plan.statements[0].sql,
        "ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS discount_code text;"
    );
}

#[test]
fn target_ddl_transaction_plan_refuses_blockers() {
    let mut input = safe_plan();
    input.blockers.push("manual review required".to_string());

    assert!(matches!(
        plan_target_ddl_transaction(input),
        Err(ApplyError::DdlApplyBlocked { barrier_id, blockers })
            if barrier_id == "ddl-barrier-123" && blockers == vec!["manual review required"]
    ));
}

