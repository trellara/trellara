#[test]
fn target_ddl_transaction_plan_rejects_unsafe_sql() {
    for sql in [
        "DROP TABLE public.sales;",
        "ALTER TABLE public.sales DROP COLUMN discount_code;",
        "ALTER TABLE public.sales RENAME COLUMN a TO b;",
        "ALTER TABLE public.sales ADD COLUMN code text NOT NULL;",
        "ALTER TABLE public.sales ADD COLUMN code text NOT\nNULL;",
        "ALTER TABLE public.sales ADD COLUMN code text DEFAULT 'new';",
        "ALTER TABLE public.sales ADD COLUMN code text\tDEFAULT('new');",
        "ALTER TABLE public.sales ADD COLUMN code text UNIQUE;",
        "ALTER TABLE public.sales ADD COLUMN account_id bigint REFERENCES public.accounts(id);",
        "ALTER TABLE public.sales ADD COLUMN quantity int CHECK (quantity > 0);",
        "ALTER TABLE public.sales ADD COLUMN normalized text GENERATED ALWAYS AS (lower(code)) STORED;",
        "ALTER TABLE public.sales ADD COLUMN row_id bigint GENERATED BY DEFAULT AS IDENTITY;",
        "ALTER TABLE public.sales ADD COLUMN code text CONSTRAINT code_not_empty CHECK (code <> '');",
        "ALTER TABLE public.sales ADD COLUMN code text PRIMARY KEY;",
        "ALTER TABLE public.sales ADD COLUMN code text; DROP TABLE public.sales;",
        "ALTER TABLE public.sales ADD COLUMN code text; -- comment",
    ] {
        let mut input = safe_plan();
        input.statements[0].sql = sql.to_string();

        assert!(matches!(
            plan_target_ddl_transaction(input),
            Err(ApplyError::UnsafeDdlStatement { .. })
        ));
    }
}

